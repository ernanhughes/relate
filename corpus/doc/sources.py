"""RELATE-DOC v0.1 source scenarios — structured experimental objects.

Each scenario is a domain fact-bundle: primary claims (load-bearing), secondary
claims, one rare/minority entity, numeric facts, temporal facts, a relation with
an argument order, and a conclusion. `generate.py` renders each into a
150-350-word document, a full atomic-claim ledger, the Family-A controlled
compressions, and (from `TRANSFORM_BASES`) the Family-B transformation pairs.

All content is invented or restated public fact in original wording (`authored` /
`adapted`). No text is drawn from an existing summarisation / faithfulness
corpus — the templated pipeline is the contamination defence (v0.1 datasheet).
"""
